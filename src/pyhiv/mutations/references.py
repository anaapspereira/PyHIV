def normalize_gene(gene: str) -> str:
    """Return the canonical mutation gene code."""
    key = str(gene or "").strip().upper().replace("_", "-")
    key = " ".join(key.split())
    compact = key.replace(" ", "")
    if key in GENE_ALIASES:
        return GENE_ALIASES[key]
    if compact in GENE_ALIASES:
        return GENE_ALIASES[compact]
    raise ValueError(f"Unsupported gene for mutation calling: {gene!r}.")


def reference_for_gene(gene: str) -> str:
    """Return the Consensus B amino-acid sequence for a supported gene."""
    canonical_gene = normalize_gene(gene)
    return CONSENSUS_B_AMINO_ACIDS[canonical_gene]
